    for release in releases:
        contracts = []
        for note in release["notes"]:
            total_notes += 1
            if is_commonish(note):
                skipped_commonish.append({"version": release["version"], "note": note})
                continue
            matched = False
            for rule in RULES:
                if not rule.matches(note):
                    continue
                matched = True
                contracts.append({
                    "name": rule.name,
                    "capability": rule.capability,
                    "evidence": note,
                    "setup": list(rule.setup),
                    "actions": list(rule.actions),
                    "assertions": list(rule.assertions),
                    "mutant": rule.mutant,
                    "rule_reason": rule.reason,
                })
            if not matched:
                unmatched.append({"version": release["version"], "note": note})
        if contracts:
            total_contracts += len(contracts)
            extracted_by_release.append({
                "version": release["version"],
                "date": release["date"],
                "bullet_count": len(release["notes"]),
                "contract_count": len(contracts),
                "contracts": contracts,
            })

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    rpl_lines = [
        "# Generated by tools/replay/extract_okhttp_contracts.py",
        "# OkHttp-origin extraction, excluding contracts judged to duplicate the existing urllib3-origin common set.",
        "",
    ]
    for release in extracted_by_release:
        rpl_lines.append(f'release "okhttp" version "{release["version"]}" date "{release["date"]}"')
        rpl_lines.append(f'source "okhttp-changelog:{release["version"]}"')
        rpl_lines.append("")
        for contract in release["contracts"]:
            rpl_lines.append(contract_block(release, contract))
            rpl_lines.append("")
    OUT_RPL.write_text("\n".join(rpl_lines).rstrip() + "\n")

    summary = {
        "source_files": [str(path.relative_to(ROOT)) for path in SOURCE_FILES],
        "output": str(OUT_RPL.relative_to(ROOT)),
        "release_count_scanned": len(releases),
        "release_count_with_contracts": len(extracted_by_release),
        "note_count_scanned": total_notes,
        "contract_count": total_contracts,
        "commonish_skipped_count": len(skipped_commonish),
        "unmatched_note_count": len(unmatched),
        "releases": extracted_by_release,
        "skipped_commonish": skipped_commonish,
        "unmatched_notes": unmatched,
    }
    OUT_JSON.write_text(json.dumps(summary, indent=2, sort_keys=True) + "\n")

    audit_lines = [
        "# OkHttp Origin Extraction Audit",
        "",
        f"- releases_scanned: {len(releases)}",
        f"- notes_scanned: {total_notes}",
        f"- contracts_extracted: {total_contracts}",
        f"- commonish_skipped: {len(skipped_commonish)}",
        f"- unmatched_notes: {len(unmatched)}",
        "",
        "## Contracts By Release",
        "",
        "| version | date | notes | contracts |",
        "|---:|---:|---:|---:|",
    ]
    for release in extracted_by_release:
        audit_lines.append(f"| {release['version']} | {release['date']} | {release['bullet_count']} | {release['contract_count']} |")
    audit_lines += ["", "## Skipped As Existing Common-ish", ""]
    for row in skipped_commonish[:200]:
        audit_lines.append(f"- {row['version']}: {row['note']}")
    audit_lines += ["", "## Unmatched New/Fix Notes", ""]
    for row in unmatched[:300]:
        audit_lines.append(f"- {row['version']}: {row['note']}")
    OUT_AUDIT.write_text("\n".join(audit_lines) + "\n")

    print(json.dumps({
        "release_count_scanned": len(releases),
        "release_count_with_contracts": len(extracted_by_release),
        "note_count_scanned": total_notes,
        "contract_count": total_contracts,
        "commonish_skipped_count": len(skipped_commonish),
        "unmatched_note_count": len(unmatched),
        "out": str(OUT_RPL.relative_to(ROOT)),
    }, indent=2))
    return 0


