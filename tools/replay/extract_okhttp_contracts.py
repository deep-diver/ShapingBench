def normalize(text: str) -> str:
    return re.sub(r"\s+", " ", text.replace("¶", "")).strip()


def parse_markdown_changelog(path: Path) -> list[dict]:
    text = path.read_text()
    releases: list[dict] = []
    current: dict | None = None
    lines = text.splitlines()
    i = 0
    while i < len(lines):
        line = lines[i]
        m = re.match(r"## Version (.+)", line)
        if m:
            current = {"version": m.group(1).strip(), "date": "", "notes": []}
            releases.append(current)
            i += 1
            continue
        if current:
            dm = re.match(r"_(\d{4}-\d{2}-\d{2})_", line.strip())
            if dm:
                current["date"] = dm.group(1)
            bm = re.match(r"\s*\*\s+(New|Fix|Change|Security|Deprecated|Remove):?\s+(.*)", line)
            if bm:
                parts = [bm.group(2).strip()]
                i += 1
                while i < len(lines):
                    nxt = lines[i]
                    if re.match(r"## Version ", nxt) or re.match(r"\s*\*\s+(New|Fix|Change|Security|Deprecated|Remove|Upgrade):?", nxt):
                        i -= 1
                        break
                    if nxt.strip() and not nxt.strip().startswith("```") and not nxt.strip().startswith("|"):
                        parts.append(nxt.strip())
                    i += 1
                current["notes"].append(normalize(" ".join(parts)))
        i += 1
    return releases


def parse_legacy_text(path: Path) -> list[dict]:
    lines = path.read_text().splitlines()
    releases: list[dict] = []
    current: dict | None = None
    in_body = False
    i = 0
    while i < len(lines):
        line = lines[i].strip()
        if re.match(r"OkHttp \d\.x Change Log", line):
            in_body = True
        if not in_body:
            i += 1
            continue
        m = re.match(r"Version ([0-9][^\s¶]*)", line)
        if m:
            current = {"version": m.group(1).strip(), "date": "", "notes": []}
            releases.append(current)
            i += 1
            continue
        if current and re.match(r"\d{4}-\d{2}-\d{2}", line):
            current["date"] = line[:10]
        if current and re.match(r"(New|Fix|Change|Security|Deprecated|Remove):", line):
            parts = [line]
            i += 1
            while i < len(lines):
                nxt = lines[i].strip()
                if re.match(r"Version [0-9]", nxt) or re.match(r"(New|Fix|Change|Security|Deprecated|Remove|Upgrade):", nxt):
                    i -= 1
                    break
                if nxt and not nxt.startswith("¶"):
                    parts.append(nxt)
                i += 1
            current["notes"].append(normalize(" ".join(parts)))
        i += 1
    return releases


def all_releases() -> list[dict]:
    releases = parse_markdown_changelog(SOURCE_FILES[0])
    for path in SOURCE_FILES[1:]:
        releases.extend(parse_legacy_text(path))
    seen = set()
    unique = []
    for release in releases:
        key = release["version"]
        if key in seen:
            continue
        seen.add(key)
        unique.append(release)
    return unique


def is_commonish(note: str) -> bool:
    return any(re.search(pattern, note) for pattern in COMMONISH_PATTERNS)


def contract_block(release: dict, contract: dict) -> str:
    lines = [
        f'contract "{contract["name"]}"',
        f'evidence "{contract["evidence"].replace(chr(34), chr(39))}"',
        f'capability "{contract["capability"]}"',
        'replay "template"',
        f'mutant "{contract["mutant"]}"',
    ]
    lines.extend(contract["setup"])
    lines.extend(contract["actions"])
    lines.extend(contract["assertions"])
    lines.append("end")
    return "\n".join(lines)


